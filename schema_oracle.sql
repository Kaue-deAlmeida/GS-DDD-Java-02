CREATE TABLE T_OC_UBS (
    id_ubs NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cnes VARCHAR2(20) NOT NULL UNIQUE,
    nome VARCHAR2(120) NOT NULL,
    endereco VARCHAR2(200) NOT NULL,
    cidade VARCHAR2(100) NOT NULL,
    bairro VARCHAR2(100) NOT NULL,
    horario_abertura VARCHAR2(5) NOT NULL,
    horario_fechamento VARCHAR2(5) NOT NULL
);

CREATE TABLE T_OC_IDOSO (
    id_idoso NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    telefone VARCHAR2(20) NOT NULL,
    rua_numero VARCHAR2(150) NOT NULL,
    cidade VARCHAR2(100) NOT NULL,
    bairro VARCHAR2(100) NOT NULL,
    horario_checkin_manha VARCHAR2(5) NOT NULL,
    horario_checkin_tarde VARCHAR2(5) NOT NULL,
    consentimento NUMBER(1) NOT NULL CHECK (consentimento IN (0, 1)),
    sem_familia NUMBER(1) DEFAULT 0 NOT NULL CHECK (sem_familia IN (0, 1)),
    id_ubs NUMBER NOT NULL,
    CONSTRAINT fk_idoso_ubs FOREIGN KEY (id_ubs) REFERENCES T_OC_UBS(id_ubs)
);

CREATE TABLE T_OC_CONTATO_FAMILIA (
    id_contato NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_idoso NUMBER NOT NULL,
    nome VARCHAR2(120) NOT NULL,
    telefone VARCHAR2(20) NOT NULL,
    ordem_prioridade NUMBER(1) NOT NULL,
    contato_extra NUMBER(1) DEFAULT 0 NOT NULL CHECK (contato_extra IN (0, 1)),
    status_convite VARCHAR2(20) NOT NULL,
    CONSTRAINT fk_contato_idoso FOREIGN KEY (id_idoso) REFERENCES T_OC_IDOSO(id_idoso)
);

CREATE TABLE T_OC_ALERTA_CALOR (
    id_alerta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade VARCHAR2(100) NOT NULL,
    data_alerta DATE NOT NULL,
    orientacoes VARCHAR2(500) NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL CHECK (ativo IN (0, 1))
);

CREATE TABLE T_OC_CHECKIN (
    id_checkin NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_idoso NUMBER NOT NULL,
    data_hora_agendada TIMESTAMP NOT NULL,
    data_hora_resposta TIMESTAMP,
    status VARCHAR2(30) NOT NULL,
    tentativas_alarme NUMBER(1) DEFAULT 1 NOT NULL,
    localizacao_emergencia VARCHAR2(120),
    CONSTRAINT fk_checkin_idoso FOREIGN KEY (id_idoso) REFERENCES T_OC_IDOSO(id_idoso)
);

CREATE TABLE T_OC_ESCALACAO (
    id_escalacao NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_checkin NUMBER NOT NULL,
    id_idoso NUMBER NOT NULL,
    etapa_atual VARCHAR2(20) NOT NULL,
    status_familia VARCHAR2(30),
    prioridade_ubs VARCHAR2(15),
    motivo_ubs VARCHAR2(150),
    reagendado_para TIMESTAMP,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_esc_checkin FOREIGN KEY (id_checkin) REFERENCES T_OC_CHECKIN(id_checkin),
    CONSTRAINT fk_esc_idoso FOREIGN KEY (id_idoso) REFERENCES T_OC_IDOSO(id_idoso)
);

CREATE TABLE T_OC_VISITA_UBS (
    id_visita NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_escalacao NUMBER NOT NULL,
    id_ubs NUMBER NOT NULL,
    id_idoso NUMBER NOT NULL,
    desfecho VARCHAR2(35) NOT NULL,
    observacao VARCHAR2(300),
    registrado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_visita_esc FOREIGN KEY (id_escalacao) REFERENCES T_OC_ESCALACAO(id_escalacao),
    CONSTRAINT fk_visita_ubs FOREIGN KEY (id_ubs) REFERENCES T_OC_UBS(id_ubs),
    CONSTRAINT fk_visita_idoso FOREIGN KEY (id_idoso) REFERENCES T_OC_IDOSO(id_idoso)
);

